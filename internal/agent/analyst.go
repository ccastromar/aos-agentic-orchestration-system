type Analyst struct {
	bus          *bus.Bus
	inbox        chan bus.Message
	llmClient    llm.LLMClient
	llmMutex     sync.RWMutex
	eventBus *bus.Bus
	stateManager *state.StateManager
}

func (a *Analyst) SetLLMClient(c llm.LLMClient) {
	a.llmMutex.Lock()
	defer a.llmMutex.Unlock()
	a.llmClient = c
}

func (a *Analyst) getLLMClient() llm.LLMClient {
	a.llmMutex.RLock()
	defer a.llmMutex.RUnlock()
	return a.llmClient
}

func NewAnalyst(b *bus.Bus, llmClient llm.LLMClient, eventBus *bus.Bus, stateManager *state.StateManager) *Analyst {
	return &Analyst{
		bus:          b,
		inbox:        make(chan bus.Message, 16),
		llmClient:    llmClient,
		eventBus: eventBus,
		stateManager: stateManager,
	}
}

func (a *Analyst) Inbox() chan bus.Message {
	return a.inbox
}
func (a *Analyst) Start(ctx context.Context) error {
	defer func() {
		if r := recover(); r != nil {
			logx.Error("Analyst", "panic recovered in Start: %v", r)
		}
	}()
	for {
		select {
		case msg := <-a.inbox:
			func() {
				defer func() {
					if r := recover(); r != nil {
						logx.Error("Analyst", "panic recovered in dispatch: %v", r)
					}
				}()
				a.dispatch(msg)
			}()

		case <-ctx.Done():
			return nil
		}
	}
}

func (a *Analyst) dispatch(msg bus.Message) {

	switch msg.Type {
	case "summarize":
		a.handleSummarize(msg)
	default:
		logx.Warn("Analyst", "unknown message: %#v", msg)
	}

}

func (a *Analyst) handleSummarize(msg bus.Message) {
	id, ok := payload.GetString(msg.Payload, "id")
	if !ok {
		logx.Error("Analyst", "invalid payload: missing id")
		return
	}
 language, ok := payload.GetString(msg.Payload, "language")
 if !ok || language == "" {
     // Default to Spanish for backward compatibility in tests
     language = "es"
 }
	intentType, _ := msg.Payload["intent"].(string)
	rawAny := msg.Payload["rawResult"]

	raw, ok := rawAny.(map[string]any)
	if !ok {
		logx.Error("Analyst", "rawResult invalid for id=%s", id)
		storeResult(id, Result{
			Status: "error",
			Err:    "invalid rawResult: expected map[string]any, got",
		})
		return
	}

 	logx.Info("Analyst", "requesting summary to the LLM...")
	if a.eventBus != nil {
		a.eventBus.PublishEvent(id, "Analyst", "summarizing", "Requesting final summary to LLM...", "")
	}
 	// obtain task context if present
 taskCtx, _ := GetTaskContext(id)
 if taskCtx == nil {
     taskCtx = context.Background()
     NewTaskContext(taskCtx, id, 0)
 }

 var summary string
 var err error
 if a.getLLMClient() == nil {
     // No LLM available → degrade gracefully to raw only
     logx.Warn("Analyst", "LLM client is nil; skipping summarization and returning raw")
     storeResult(id, Result{
         Status: "ok",
         Data: map[string]any{
             "raw": raw,
         },
     })
     return
 }

 timer := logx.Start(id, "Analyst", "SummarizeLLM")
 summary, err = llm.SummarizeResult(taskCtx, a.getLLMClient(), intentType, raw, language)
 timer.End()

 if err != nil {
     logx.Error("Analyst", "error calling to the LLM: %v", err)
     storeResult(id, Result{
         Status: "ok",
         Data: map[string]any{
             "raw": raw,
         },
     })
     return
 }
	logx.Info("Analyst", "summary generated by LLM: %s", summary)
	//	a.eventBus.PublishEvent(id, "Analyst", "summary", "summary LLM has been generated", "")
	a.eventBus.PublishEvent(id, "Analyst", "summary", summary, "")
	a.eventBus.PublishEvent(id, "Analyst", "completed", "Pipeline completed", "")

	// Update persistent state with final results
	sessionID, _ := payload.GetString(msg.Payload, "session_id")
	pipelineName, _ := payload.GetString(msg.Payload, "pipeline")
	if a.stateManager != nil {
		st, err := a.stateManager.Load(taskCtx, id)
		if err == nil {
			if st == nil {
				// Happy-path executions never hit a gate, so no state was
				// persisted during the run; create it here or the execution
				// stays invisible to recall.
				st = &state.ExecutionState{
					ID:        id,
					SessionID: sessionID,
					Intent:    intentType,
					Pipeline:  pipelineName,
				}
			}
			if st.Pipeline == "" {
				st.Pipeline = pipelineName
			}
			pipelineName = st.Pipeline
			if st.StepResults == nil {
				st.StepResults = make(map[string]any)
			}
			st.StepResults["_pipeline"] = map[string]any{
				"raw":     raw,
				"summary": summary,
			}
			_ = a.stateManager.Save(taskCtx, st)
		}
	}

	// Vector Memory (Long-Term Storage). System intents (recall, etc.) are
	// meta-operations: remembering them would pollute memory with copies of
	// what it already contains.
	if sessionID != "" && !strings.HasPrefix(intentType, "system.") {
		if vs := a.stateManager.Vector(); vs != nil && a.getLLMClient() != nil {
			facts := extractFacts(raw)
			textToEmbed := fmt.Sprintf("Intent: %s\nPipeline: %s\nAction Summary: %s", intentType, pipelineName, summary)
			if ft := factsText(facts); ft != "" {
				textToEmbed += "\nFacts:\n" + ft
			}
			embedding, err := a.getLLMClient().Embed(taskCtx, textToEmbed)
			if err == nil {
				mem := state.Memory{
					ID:        randomID(),
					SessionID: sessionID,
					Text:      textToEmbed,
					Embedding: embedding,
					Metadata: map[string]any{
						"execution_id": id,
						"intent":       intentType,
						"pipeline":     pipelineName,
						"facts":        facts,
					},
					Timestamp: time.Now(),
				}
				_ = vs.AddMemory(taskCtx, mem)
			}
		}
	}

	storeResult(id, Result{
		Status: "completed",
		Data: map[string]any{
			"raw":     raw,
			"summary": summary,
		},
	})
}
