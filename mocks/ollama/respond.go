package ollama

import (
	"encoding/json"
	"fmt"
	"strings"
)

// Prompt markers. They mirror the fixed prompts in internal/llm; if a prompt there changes,
// the matching marker here must change too (the mock then falls back to kindUnknown).
const (
	markerIntent        = "You are the NLU module of the AOS system."
	markerIntentCatalog = "DEFINED INTENTS (DO NOT invent new ones. If no intent matches, return \"unknown\"):"
	markerIntentContext = "RECENT CONVERSATION CONTEXT:"
	markerIntentUser    = "USER MESSAGE:\n\""
	markerIntentUserEnd = "\"\n\nRESPOND WITH A SINGLE VALID JSON OBJECT ONLY."
	markerExtract       = "Extract ONLY the required parameters from the user message."
	markerExtractKeys   = "JSON MUST contain EXACTLY these keys:"
	markerExtractUser   = "User message: \""
	markerSummaryES     = "Eres un asistente multi-dominio"
	markerSummaryEN     = "You are a multi-domain assistant"
	markerSummaryRaw    = "(JSON):\n\n"
	markerSummaryRawEnd = "\n\nEl resumen debe explicar:"
	markerSummaryRawEN  = "\n\nThe summary must explain:"
	markerFallbackES    = "Eres un asistente conversacional útil e inteligente."
	markerFallbackEN    = "You are a helpful and intelligent conversational assistant."
	markerCodeGen       = "Generate production-ready "
	markerReActText     = "\"action_input\": \"A JSON object containing parameters for the tool."
)

type promptKind string

const (
	kindIntent   promptKind = "intent"
	kindExtract  promptKind = "extract_params"
	kindSummary  promptKind = "analyst_summary"
	kindFallback promptKind = "analyst_fallback"
	kindCodeGen  promptKind = "code_generation"
	kindReAct    promptKind = "react_text"
	kindUnknown  promptKind = "unknown"
)

func classify(prompt string) promptKind {
	switch {
	case strings.Contains(prompt, markerIntent):
		return kindIntent
	case strings.Contains(prompt, markerExtract):
		return kindExtract
	case strings.Contains(prompt, markerSummaryES), strings.Contains(prompt, markerSummaryEN):
		return kindSummary
	case strings.Contains(prompt, markerFallbackES), strings.Contains(prompt, markerFallbackEN):
		return kindFallback
	case strings.HasPrefix(strings.TrimSpace(prompt), markerCodeGen):
		return kindCodeGen
	case strings.Contains(prompt, markerReActText):
		return kindReAct
	default:
		return kindUnknown
	}
}

// respond produces the deterministic answer for one prompt.
func respond(prompt string, scenarios []Scenario) (promptKind, string) {
	kind := classify(prompt)
	switch kind {
	case kindIntent:
		return kind, mustJSON(detectIntent(prompt, scenarios))
	case kindExtract:
		return kind, mustJSON(extractParams(prompt, scenarios))
	case kindSummary:
		return kind, summarize(prompt, scenarios)
	case kindFallback:
		return kind, fallbackAnswer(prompt)
	case kindCodeGen:
		return kind, "// Generated by the aos-demo deterministic mock: no model wrote this code.\n"
	case kindReAct:
		return kind, mustJSON(map[string]any{
			"thought":      "Deterministic demo mock: no reasoning model is attached.",
			"action":       "FINISH",
			"action_input": "The aos-demo mock cannot run open-ended agent tasks; use a real model for this flow.",
		})
	default:
		return kind, "[aos-demo mock] This prompt is not one of the AOS prompts the deterministic mock understands."
	}
}

// userMessage extracts the end user's text from an AOS prompt, or "" if there is none.
func userMessage(prompt string) string {
	if text, ok := between(prompt, markerIntentUser, markerIntentUserEnd); ok {
		return text
	}
	if i := strings.Index(prompt, markerExtractUser); i >= 0 {
		rest := prompt[i+len(markerExtractUser):]
		if j := strings.LastIndex(rest, "\""); j >= 0 {
			return rest[:j]
		}
	}
	return ""
}

type intentAnswer struct {
	Intent     string            `json:"intent"`
	Confidence float64           `json:"confidence"`
	Language   string            `json:"language"`
	Parameters map[string]string `json:"parameters"`
	Errors     []string          `json:"errors"`
	NewFacts   []string          `json:"new_facts"`
}

type catalogEntry struct {
	Description    string   `json:"description"`
	RequiredParams []string `json:"required_params"`
	Examples       []string `json:"examples"`
}

func detectIntent(prompt string, scenarios []Scenario) intentAnswer {
	msg := userMessage(prompt)
	catalog := parseCatalog(prompt)
	answer := intentAnswer{
		Intent:     "unknown",
		Language:   detectLanguage(msg),
		Parameters: map[string]string{},
		Errors:     []string{},
		NewFacts:   []string{},
	}

	intent, params, confidence := "", map[string]string{}, 0.0
	if sc, groups := matchScenario(scenarios, msg); sc != nil {
		if _, ok := catalog[sc.Intent]; ok || len(catalog) == 0 {
			intent, confidence = sc.Intent, 0.97
			params = sc.render(groups)
		}
	}
	if intent == "" {
		intent, confidence = bestIntent(msg, catalog)
	}
	if intent == "" {
		return answer
	}

	answer.Intent = intent
	answer.Confidence = confidence
	for _, name := range catalog[intent].RequiredParams {
		value := params[name]
		if value == "" {
			value = guessParam(msg, name)
		}
		answer.Parameters[name] = value
		if value == "" {
			answer.Errors = append(answer.Errors, name)
		}
	}
	// Scenario parameters that are not required are still useful downstream.
	for k, v := range params {
		if _, ok := answer.Parameters[k]; !ok {
			answer.Parameters[k] = v
		}
	}
	return answer
}

func parseCatalog(prompt string) map[string]catalogEntry {
	raw, ok := between(prompt, markerIntentCatalog, markerIntentContext)
	if !ok {
		return map[string]catalogEntry{}
	}
	var catalog map[string]catalogEntry
	if err := json.Unmarshal([]byte(strings.TrimSpace(raw)), &catalog); err != nil {
		return map[string]catalogEntry{}
	}
	return catalog
}

func extractParams(prompt string, scenarios []Scenario) map[string]string {
	msg := userMessage(prompt)
	var keys []string
	if i := strings.Index(prompt, markerExtractKeys); i >= 0 {
		rest := strings.TrimSpace(prompt[i+len(markerExtractKeys):])
		if j := strings.Index(rest, "]"); j >= 0 {
			_ = json.Unmarshal([]byte(rest[:j+1]), &keys)
		}
	}
	fromScenario := map[string]string{}
	if sc, groups := matchScenario(scenarios, msg); sc != nil {
		fromScenario = sc.render(groups)
	}
	out := map[string]string{}
	for _, k := range keys {
		v := fromScenario[k]
		if v == "" {
			v = guessParam(msg, k)
		}
		out[k] = v
	}
	return out
}

func fallbackAnswer(prompt string) string {
	if strings.Contains(prompt, markerFallbackES) {
		return "Soy el modelo de demostración determinista de AOS: no genero respuestas libres. Prueba con una de las operaciones definidas en el catálogo de intenciones."
	}
	return "I am the AOS deterministic demo model: I do not generate open-ended answers. Try one of the operations defined in the intent catalog."
}

func between(s, start, end string) (string, bool) {
	i := strings.Index(s, start)
	if i < 0 {
		return "", false
	}
	rest := s[i+len(start):]
	j := strings.Index(rest, end)
	if j < 0 {
		return "", false
	}
	return rest[:j], true
}

func mustJSON(v any) string {
	b, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		return fmt.Sprintf("{\"error\": %q}", err.Error())
	}
	return string(b)
}
